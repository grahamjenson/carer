// Writes integration_test/flows.g.dart, the UI flows' files (test/flows) for a phone, which cannot read them from here:
// dart run tool/bundle_flows.dart
import 'dart:convert';
import 'dart:io';

const flowsDir = "test/flows";
const bundlePath = "integration_test/flows.g.dart";

String bundleFlows() {
  var files = Directory(flowsDir).listSync(recursive: true).whereType<File>().where((f) => !f.path.endsWith(".dart"));
  var paths = files.map((f) => f.path.substring(flowsDir.length + 1)).where((p) => p != "README.md").toList()..sort();
  var entries = paths.map((p) {
    var contents = jsonEncode(File("$flowsDir/$p").readAsStringSync()).replaceAll(r"$", r"\$");
    return "  ${jsonEncode(p)}: $contents,\n";
  });
  return "// Generated by tool/bundle_flows.dart from test/flows. Do not edit.\n\nconst flowFiles = <String, String>{\n${entries.join()}};\n";
}

void main() => File(bundlePath).writeAsStringSync(bundleFlows());
